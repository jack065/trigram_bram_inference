"""Train the model and export everything the hardware needs into hw/.

hw/weights.mem      NBUCKETS x 32-bit words, {w3, w2, w1, w0} int8 per bucket
hw/bias.mem         4 x 32-bit two's complement biases (accumulator scale)
hw/exp_lut.mem      round(exp(-d * scale) * 2^16) for d = 0 .. LUT_DEPTH-1, 16-bit
hw/model_params.vh  sizes, threshold constant and the H3 hash function
hw/vectors.txt      test sentences with the exact expected accumulators and class

The expected values come from hw_predict(), a bit-exact model of the RTL.
"""
import os
import math
import numpy as np
from train import (H3_Q, NBUCKETS, THRESHOLD, UNKNOWN, featurize, hash_trigram,
                   load_clinc, load_data, predict_int8, quantize_int8, train_model)

OUT_DIR = 'hw'
EXP_FRAC_BITS = 16
N_CLINC_VECTORS = 460
PUNCT = set(b'!"#$%&\'()*+,-./:;<=>?@[\\]^_`{|}~')
EDGE_CASES = ['a', 'ab', 'abc', '!!!', 'A.B.C.D', 'BOOK A FLIGHT TO BOSTON!!!',
              'how many calories in a banana ' * 8, '   ', 'x?y?z?w']

def normalize_bytes(data):
    # What the RTL does per byte: drop ASCII punctuation, lowercase A-Z.
    return bytes(b | 0x20 if 0x41 <= b <= 0x5A else b for b in data if b not in PUNCT)

def build_exp_lut(scale):
    lut = []
    d = 0
    while True:
        v = min(round(math.exp(-d * scale) * (1 << EXP_FRAC_BITS)), (1 << EXP_FRAC_BITS) - 1)
        lut.append(v)
        if v == 0:
            break
        d += 1
    bits = max(1, math.ceil(math.log2(len(lut))))
    return lut + [0] * ((1 << bits) - len(lut)), bits

def hw_predict(data, W_q, b_q, lut, thresh_sum):
    acc = [int(b) for b in b_q]
    n = normalize_bytes(data)
    for i in range(len(n) - 2):
        h = hash_trigram(n[i], n[i + 1], n[i + 2])
        for k in range(4):
            acc[k] += int(W_q[k, h])
    argmax = max(range(4), key=lambda k: (acc[k], -k))  # first max, like np.argmax
    s = sum(lut[min(acc[argmax] - acc[k], len(lut) - 1)] for k in range(4) if k != argmax)
    cls = UNKNOWN if argmax == UNKNOWN or s > thresh_sum else argmax
    return acc, argmax, cls

def main():
    assert NBUCKETS & (NBUCKETS - 1) == 0 and max(H3_Q) < NBUCKETS
    os.makedirs(OUT_DIR, exist_ok=True)
    clf, _ = train_model()
    W_q, b_q, scale = quantize_int8(clf)
    nb_bits = NBUCKETS.bit_length() - 1
    lut, lut_bits = build_exp_lut(scale)
    thresh_sum = math.floor((1 / THRESHOLD - 1) * (1 << EXP_FRAC_BITS))

    packed = np.ascontiguousarray(W_q.T).view('<u4').ravel()
    with open(f'{OUT_DIR}/weights.mem', 'w') as f:
        f.writelines(f'{w:08x}\n' for w in packed)
    with open(f'{OUT_DIR}/bias.mem', 'w') as f:
        f.writelines(f'{int(b) & 0xffffffff:08x}\n' for b in b_q)
    with open(f'{OUT_DIR}/exp_lut.mem', 'w') as f:
        f.writelines(f'{v:04x}\n' for v in lut)
    np.save(f'{OUT_DIR}/weights_packed.npy', packed)
    np.save(f'{OUT_DIR}/bias.npy', b_q)

    with open(f'{OUT_DIR}/model_params.vh', 'w') as f:
        f.write(f'// Generated by export.py (scale {scale:.8f}, threshold {THRESHOLD})\n')
        f.write(f'localparam NB_BITS    = {nb_bits};\n')
        f.write(f'localparam LUT_BITS   = {lut_bits};\n')
        f.write(f'localparam THRESH_SUM = {thresh_sum};  // accept if sum of exp terms <= this\n\n')
        f.write('function [NB_BITS-1:0] h3;\n    input [23:0] x;\n    begin\n')
        f.write("        h3 = {NB_BITS{1'b0}};\n")
        for i, q in enumerate(H3_Q):
            f.write(f"        if (x[{i}]) h3 = h3 ^ {nb_bits}'d{q};\n")
        f.write('    end\nendfunction\n')

    texts = load_data()[0]
    te_text, _ = load_clinc(['test', 'oos_test'])
    rng = np.random.default_rng(0)
    texts += [te_text[i] for i in rng.choice(len(te_text), N_CLINC_VECTORS, replace=False)]
    texts += EDGE_CASES
    texts = [t for t in texts if t.isascii() and t]

    float_pred, _ = predict_int8(W_q, b_q, scale, np.stack([featurize(t) for t in texts]))
    agree = 0
    with open(f'{OUT_DIR}/vectors.txt', 'w') as f:
        for t, fp in zip(texts, float_pred):
            data = t.encode('ascii')
            acc, argmax, cls = hw_predict(data, W_q, b_q, lut, thresh_sum)
            agree += cls == fp
            f.write(f'{len(data):x} ' + ' '.join(f'{b:02x}' for b in data) + ' '
                    + ' '.join(f'{a & 0xffffffff:08x}' for a in acc) + f' {argmax:x} {cls:x}\n')

    print(f'Wrote {OUT_DIR}/: {NBUCKETS} weight words, exp LUT {len(lut)} x {EXP_FRAC_BITS} bit, '
          f'{len(texts)} test vectors')
    print(f'scale {scale:.8f}, THRESH_SUM {thresh_sum}, bias {b_q.tolist()}')
    print(f'Fixed-point model vs float model: {agree}/{len(texts)} predictions agree')

if __name__ == '__main__':
    main()
